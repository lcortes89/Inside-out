package org.luisa.diary.models;

/**
 * Represents the emotion associated with a moment.
 */
public enum Emotion {

    /** Joy. */
    ALEGRIA,

    /** Sadness. */
    TRISTEZA,

    /** Anger. */
    IRA,

    /** Disgust. */
    ASCO,

    /** Fear. */
    MIEDO,

    /** Anxiety. */
    ANSIEDAD,

    /** Envy. */
    ENVIDIA,

    /** Shame. */
    VERGUENZA,

    /** Boredom. */
    ABURRIMIENTO,

    /** Nostalgia. */
    NOSTALGIA;
}